export type AccountMessageKey = keyof (typeof messages)["en"];

export function ta(
  locale: Locale,
  key: AccountMessageKey,
  values: Record<string, string | number> = {},
): string {
  const template = messages[locale][key] ?? messages[DEFAULT_LOCALE as Locale][key];
  return template.replace(/\{(\w+)\}/g, (_m, name: string) => String(values[name] ?? `{${name}}`));
}

export function assertAccountCatalogCompleteness(): void {
  const keys = Object.keys(messages.en) as AccountMessageKey[];
  for (const locale of SUPPORTED_LOCALES as readonly Locale[]) {
    const missing = keys.filter((key) => messages[locale][key] === undefined);
    if (missing.length > 0) {
      throw new Error(`Missing ${locale} account translations: ${missing.join(", ")}`);
    }
  }
}
