export type StudioUiCopy = (typeof COPY)[StudioUiLocale];

export function copyFor(locale: StudioUiLocale): StudioUiCopy {
  return COPY[locale];
}

export function taskTitle(task: AgentTask, copy: StudioUiCopy): string {
  if (task.id === "first-step") return copy.taskFirstStep;
  if (task.id === "repeat-pattern") return copy.taskRepeatPattern;
  return task.title;
}
